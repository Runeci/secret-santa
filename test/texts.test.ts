import { describe, expect, it } from "vitest";
import { giftsLabel } from "../src/texts";

describe("giftsLabel: склонение", () => {
  it.each([
    [0, "нет подарков"], [1, "1 подарок"], [2, "2 подарка"], [3, "3 подарка"], [4, "4 подарка"], [5, "5 подарков"],
    [11, "11 подарков"], [12, "12 подарков"], [14, "14 подарков"], [20, "20 подарков"],
    [21, "21 подарок"], [22, "22 подарка"], [25, "25 подарков"], [101, "101 подарок"], [111, "111 подарков"],
  ])("%i → %s", (n, expected) => expect(giftsLabel(n)).toBe(expected));
});
